"""Detecting what changed between two runs of the same competitor.

Re-running a competitor analysis is only worth doing if the second run can say
what moved. Without that, a report reader has two documents and no way to tell a
real change from a reworded page, and the pull towards reading every difference
as a change is strong — vendors edit their marketing constantly.

So the diff is narrow on purpose. A ``ChangeEvent`` is emitted only where a
*comparable* field changed, and a field nobody put in the comparison table is not
comparable at all. Adding a blog post is not a pricing change.

The interesting design problem is absence, and it is the same one the rest of
this system keeps meeting. A field that was known and is now missing is a change;
a field that was never known is not. If they were treated alike, every company
would accumulate a stream of "changes" on each run describing the same gaps, and
the signal that matters — a price that moved, a free tier that appeared — would
be buried under noise generated by the absence of data rather than by the market.
"""

from __future__ import annotations

from datetime import UTC, datetime

from app.services.change_detection import (
    ChangeDetector,
    CompetitorSnapshot,
)

NOW = datetime.now(UTC)


def _detector(**overrides) -> ChangeDetector:
    return ChangeDetector(**overrides)


def _previous() -> dict[str, dict[str, object]]:
    return {
        "Acme": {
            "starter_price": {"value": 10, "url": "https://acme.example/pricing"},
            "has_free_tier": {"value": False, "url": "https://acme.example/pricing"},
            "plan_name": {"value": "Starter"},
        },
        "Beta": {"starter_price": {"value": 20, "url": "https://beta.example/pricing"}},
    }


def _current() -> dict[str, dict[str, object]]:
    return {
        "Acme": {
            "starter_price": {"value": 15, "url": "https://acme.example/pricing"},
            "has_free_tier": {"value": False, "url": "https://acme.example/pricing"},
            "plan_name": {"value": "Starter"},
        },
        "Beta": {"starter_price": {"value": 20, "url": "https://beta.example/pricing"}},
    }


class TestTheChangedPrice:
    """The plan's fifth required failure."""

    def test_one_changed_price_emits_exactly_one_event(self) -> None:
        """Required: exactly one ``pricing`` event, not one per company."""
        events = _detector().diff(_previous(), _current())
        assert len(events) == 1
        assert events[0].change_type == "pricing"

    def test_the_event_names_the_company(self) -> None:
        event = _detector().diff(_previous(), _current())[0]
        assert event.company == "Acme"

    def test_the_event_carries_both_values(self) -> None:
        event = _detector().diff(_previous(), _current())[0]
        assert event.previous_value["value"] == 10
        assert event.new_value["value"] == 15

    def test_the_event_is_stamped_with_a_detection_time(self) -> None:
        event = _detector().diff(_previous(), _current())[0]
        assert event.detected_at

    def test_the_event_names_the_source_it_came_from(self) -> None:
        event = _detector().diff(_previous(), _current())[0]
        assert event.source == "https://acme.example/pricing"

    def test_the_stamp_parses_as_a_timestamp(self) -> None:
        event = _detector().diff(_previous(), _current())[0]
        assert datetime.fromisoformat(event.detected_at)

    def test_an_unchanged_run_emits_nothing(self) -> None:
        """A diff that always reports something is a diff nobody reads."""
        assert _detector().diff(_previous(), _previous()) == []

    def test_the_unchanged_competitor_is_not_reported(self) -> None:
        events = _detector().diff(_previous(), _current())
        assert all(event.company != "Beta" for event in events)

    def test_two_changed_fields_emit_two_events(self) -> None:
        current = _current()
        current["Acme"]["has_free_tier"] = {"value": True, "url": "https://acme.example/x"}
        events = _detector().diff(_previous(), current)
        assert {event.change_type for event in events} == {"pricing", "feature"}
        assert len(events) == 2


class TestAbsenceIsNotAChange:
    def test_a_field_removed_from_the_comparison_is_not_a_change(self) -> None:
        """No observation, not an observation of nothing."""
        current = _current()
        del current["Acme"]["plan_name"]
        events = _detector().diff(_previous(), current)
        assert all("plan_name" not in str(event.new_value) for event in events)

    def test_a_field_newly_known_is_a_change(self) -> None:
        """The other half: appearing is as real a change as moving."""
        previous = {"Beta": {"starter_price": {"value": 20}}}
        current = {
            "Beta": {
                "starter_price": {"value": 20},
                "enterprise_tier": {"value": "Enterprise", "url": "u"},
            }
        }
        events = _detector().diff(previous, current)
        assert len(events) == 1
        assert events[0].company == "Beta"
        assert events[0].previous_value == {}

    def test_a_competitor_only_in_the_new_run_is_a_company_not_a_change(self) -> None:
        current = _current()
        current["Gamma"] = {"starter_price": {"value": 5, "url": "https://gamma.example"}}
        events = _detector().diff(_previous(), current)
        assert all(event.company != "Gamma" for event in events)

    def test_a_competitor_only_in_the_old_run_emits_nothing(self) -> None:
        """A dropped competitor is a research outcome, not a change in a price.

        The other competitor's fields are held identical so this measures the
        dropped company rather than the price change the fixtures also contain.
        """
        previous = {"Acme": dict(_current()["Acme"]), "Beta": {"starter_price": {"value": 20}}}
        events = _detector().diff(previous, {"Acme": dict(_current()["Acme"])})
        assert events == []


class TestValueComparison:
    def test_a_string_change_is_detected(self) -> None:
        previous = {"Acme": {"plan_name": {"value": "Starter"}}}
        current = {"Acme": {"plan_name": {"value": "Basic"}}}
        assert len(_detector().diff(previous, current)) == 1

    def test_a_case_only_change_is_a_change(self) -> None:
        """Vendors do change capitalisation, and a reader comparing runs wants to know."""
        previous = {"Acme": {"plan_name": {"value": "starter"}}}
        current = {"Acme": {"plan_name": {"value": "Starter"}}}
        assert len(_detector().diff(previous, current)) == 1

    def test_a_numeric_change_of_type_is_detected(self) -> None:
        """10 and "10" are different facts, however alike they look in a table."""
        previous = {"Acme": {"price": {"value": 10}}}
        current = {"Acme": {"price": {"value": "10"}}}
        assert len(_detector().diff(previous, current)) == 1

    def test_a_list_reordering_is_a_change(self) -> None:
        previous = {"Acme": {"features": {"value": ["a", "b"]}}}
        current = {"Acme": {"features": {"value": ["b", "a"]}}}
        assert len(_detector().diff(previous, current)) == 1

    def test_a_missing_value_in_both_runs_is_not_a_change(self) -> None:
        previous = {"Acme": {"price": {}}}
        current = {"Acme": {"price": {}}}
        assert _detector().diff(previous, current) == []

    def test_a_plain_scalar_is_accepted(self) -> None:
        """Not every caller wraps its values; the detector should cope."""
        previous = {"Acme": {"price": 10}}
        current = {"Acme": {"price": 15}}
        events = _detector().diff(previous, current)
        assert len(events) == 1
        assert events[0].previous_value == {"value": 10}


class TestChangeTypes:
    def test_a_price_field_is_a_pricing_change(self) -> None:
        """Resolved through the detector, not by indexing the mapping.

        The mapping is matched by substring, so a field's type is whatever
        ``change_type`` says it is — the test asserts the public answer rather
        than the shape of the table behind it.
        """
        assert _detector().change_type("starter_price") == "pricing"

    def test_a_free_tier_field_is_a_feature_change(self) -> None:
        assert _detector().change_type("has_free_tier") == "feature"

    def test_the_longest_matching_key_wins(self) -> None:
        """``free_tier`` is a feature; the bare ``tier`` would say pricing."""
        assert _detector().change_type("free_tier") == "feature"
        assert _detector().change_type("enterprise_tier") == "pricing"

    def test_an_unknown_field_falls_back_to_a_generic_type(self) -> None:
        """Not an exception: an unmapped field is still a change worth reporting."""
        previous = {"Acme": {"mystery": {"value": 1}}}
        current = {"Acme": {"mystery": {"value": 2}}}
        assert _detector().diff(previous, current)[0].change_type == "other"

    def test_a_caller_can_map_its_own_fields(self) -> None:
        previous = {"Acme": {"headcount_band": {"value": "11-50"}}}
        current = {"Acme": {"headcount_band": {"value": "51-200"}}}
        detector = _detector(field_types={"headcount_band": "hiring"})
        assert detector.diff(previous, current)[0].change_type == "hiring"

    def test_a_substring_of_a_known_field_is_matched(self) -> None:
        """``acme_starter_price_monthly`` is still a price."""
        previous = {"Acme": {"acme_starter_price_monthly": {"value": 10}}}
        current = {"Acme": {"acme_starter_price_monthly": {"value": 12}}}
        assert _detector().diff(previous, current)[0].change_type == "pricing"

    def test_a_company_prefixed_field_is_matched(self) -> None:
        previous = {"Acme": {"beta_price_monthly": {"value": 10}}}
        current = {"Acme": {"beta_price_monthly": {"value": 12}}}
        assert _detector().diff(previous, current)[0].change_type == "pricing"


class TestTheSnapshot:
    def test_a_snapshot_is_built_from_a_comparison_table(self) -> None:
        snapshot = CompetitorSnapshot.from_fields(
            {"Acme": {"starter_price": {"value": 10, "source_ids": ["s1"]}}}
        )
        assert snapshot.fields("Acme")["starter_price"]["value"] == 10

    def test_a_snapshot_keeps_its_company_names(self) -> None:
        snapshot = CompetitorSnapshot.from_fields({"Acme": {}, "Beta": {}})
        assert sorted(snapshot.companies) == ["Acme", "Beta"]

    def test_an_unknown_company_has_no_fields(self) -> None:
        snapshot = CompetitorSnapshot.from_fields({"Acme": {"price": 1}})
        assert snapshot.fields("Nobody") == {}

    def test_a_snapshot_round_trips_through_a_dict(self) -> None:
        snapshot = CompetitorSnapshot.from_fields({"Acme": {"price": 1}})
        assert CompetitorSnapshot.from_mapping(snapshot.as_dict()).companies == ("Acme",)

    def test_a_snapshot_sorts_its_companies(self) -> None:
        """Two snapshots of one run must be comparable, whatever order they were built in."""
        snapshot = CompetitorSnapshot.from_fields({"Beta": {}, "Acme": {}})
        assert snapshot.companies == ("Acme", "Beta")

    def test_a_plain_mapping_is_accepted_as_a_snapshot(self) -> None:
        assert len(_detector().diff({"Acme": {"p": 1}}, {"Acme": {"p": 2}})) == 1

    def test_an_empty_previous_run_emits_nothing(self) -> None:
        """A first run has nothing to compare against, and that is not a change."""
        assert _detector().diff({}, _current()) == []

    def test_an_empty_current_run_emits_nothing(self) -> None:
        assert _detector().diff(_previous(), {}) == []


class TestDetectedAt:
    def test_the_timestamp_can_be_pinned(self) -> None:
        """A test that could otherwise depend on the clock is a flaky test."""
        detector = _detector(now=lambda: datetime(2026, 9, 27, 12, 0, tzinfo=UTC))
        event = detector.diff(_previous(), _current())[0]
        assert event.detected_at.startswith("2026-09-27")

    def test_the_default_clock_is_utc(self) -> None:
        event = _detector().diff(_previous(), _current())[0]
        assert datetime.fromisoformat(event.detected_at).tzinfo is not None
